#!/usr/bin/env python3
"""Generate static HTML5 data without atob/Buffer initialization in QuickJS."""
from pathlib import Path
import html.entities
import json
output = Path(__file__).resolve().parents[1] / 'src/notes/html-entities.ts'
output.write_text('// HTML5 named character references. Generated by scripts/generate-note-entities.py.\n// Keys with a semicolon are complete names; bare keys are the HTML legacy set.\nexport const noteHtmlEntities:Readonly<Record<string,string>>=' + json.dumps(html.entities.html5, ensure_ascii=False, separators=(',', ':')) + ';\n')
